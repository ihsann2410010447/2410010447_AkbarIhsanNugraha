    public void tampilDataKaryawan(){
    DefaultTableModel KaryawanModel = new DefaultTableModel();
    KaryawanModel.addColumn("UserName");
    KaryawanModel.addColumn("Nama");
    KaryawanModel.addColumn("Alamat");
    KaryawanModel.addColumn("NomorTelepon");

    for (int i = 0; i < employee.listDatauser().size(); i++) {
        String UserName   = employee.listDatauser().get(i);
        String Nama   = employee.listDataNama().get(i);
        String Alamat = employee.listDataalamat().get(i);
        String NomorTelepon  = employee.listDatanomor().get(i).toString();

        Object[] barisData = {UserName, Nama, Alamat, NomorTelepon};
        KaryawanModel.addRow(barisData);
    }
    tblKaryawan.setModel(KaryawanModel);

        
    }

