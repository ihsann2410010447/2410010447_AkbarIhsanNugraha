    private void tblKaryawanMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblKaryawanMouseClicked
        // TODO add your handling code here:
        int baris = tblKaryawan.getSelectedRow(); 
        String UserName     = tblKaryawan.getValueAt(baris, 0).toString();
        String Nama      = tblKaryawan.getValueAt(baris, 1).toString();
        String Alamat    = tblKaryawan.getValueAt(baris, 2).toString();
        String NomorTelepon     = tblKaryawan.getValueAt(baris, 3).toString();
        txtUserName.setText(UserName);
        txtNama.setText(Nama);
        txtAlamat.setText(Alamat);
        txtNomorTelepon.setText(NomorTelepon);
    }//GEN-LAST:event_tblKaryawanMouseClicked

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        employee.inputDataUser(txtUserName.getText());
        employee.inputDataNama(txtNama.getText());
        employee.inputDataalamat(txtAlamat.getText());
        employee.inputDatanomor(Integer.parseInt(txtNomorTelepon.getText()));
        tampilDataKaryawan();
    }//GEN-LAST:event_jButton1ActionPerformed

